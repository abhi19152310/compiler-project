"""Semantic tree renderer and deterministic reusable CSS for expanded components."""

from html import escape
import re

from .properties import CSS_KEYS, SIZES, color

TAGS = {"heading": "h1", "paragraph": "p", "image": "img", "link": "a", "container": "div",
        "card": "article", "hero": "section", "submit": "button"}
BASE = """/* Generated by Text2Web. */
* { box-sizing: border-box; }
body { margin: 0; background: #ffffff; color: #111827; font-family: Arial, sans-serif; line-height: 1.6; overflow-wrap: anywhere; }
.page { max-width: 1200px; margin: 0 auto; padding: 40px 24px; }
h1, h2, h3, h4, h5, h6 { line-height: 1.2; margin: 0 0 16px; }
p { margin: 0 0 20px; white-space: pre-wrap; }
a { color: #2b6cb0; }
:focus-visible { outline: 3px solid #2b6cb0; outline-offset: 3px; }
"""
COMPONENT_CSS = {
    "nav": '.nav { display: flex; flex-wrap: wrap; align-items: center; gap: 20px; padding: 16px 0; }',
    "container": '.container { min-width: 0; }',
    "card": '.card { min-width: 0; padding: 24px; border: 1px solid #cbd5e1; border-radius: 12px; display: flex; flex-direction: column; gap: 16px; }\n.card > :last-child { margin-top: auto; }',
    "hero": '.hero { padding: 48px 24px; }',
    "image": 'img { max-width: 100%; height: auto; object-fit: contain; }',
    "form": '.form { display: flex; flex-direction: column; gap: 12px; max-width: 640px; }\n.form input, .form textarea, .form select { max-width: 100%; min-width: 0; font: inherit; padding: 10px; border: 1px solid #64748b; border-radius: 6px; }\n.static-form-note { font-size: 0.875rem; }',
    "table": '.table-scroll { max-width: 100%; overflow-x: auto; }\ntable { border-collapse: collapse; width: 100%; }\nth, td { text-align: left; border: 1px solid #64748b; padding: 10px; }',
    "button": 'button, .button-link { font: inherit; padding: 12px 20px; border: 1px solid #64748b; border-radius: 6px; }\n.button-link { display: inline-block; }',
}


def declarations(props, kind):
    """Return a canonical property map; later explicit properties beat presets."""
    output = {}
    for key, value in props.items():
        if key not in CSS_KEYS or key.startswith("hover-"):
            continue
        if key == "size":
            output.setdefault("font-size", SIZES[value])
        elif key == "columns":
            output["grid-template-columns"] = f'repeat({value}, minmax(0, 1fr))'
        elif key == "box-shadow":
            output[key] = '0 4px 16px rgba(0, 0, 0, 0.08)' if value == "subtle" else "none"
        elif key == "transition":
            output[key] = 'color 150ms ease, background-color 150ms ease' if value == "smooth" else "none"
        elif key == "background-image":
            # Quotes, backslashes and markup delimiters were rejected by validation.
            output[key] = f'url("{value}")'
        elif key == "font-family":
            output[key] = 'Arial, sans-serif' if value == 'arial' else value
        elif key == "font-weight":
            output[key] = {"bold": "700", "normal": "400"}.get(value, value)
        elif key == "text-color":
            output["color"] = color(value)
        else:
            output[key] = color(value) if key.endswith("color") else value
    if kind in {"button", "submit"} and "color" in props:
        output["background-color"] = color(props.get("background-color", props["color"]))
        output["color"] = color(props.get("text-color", "black" if props["color"] == "white" else "white"))
    if props.get("responsive") == "true":
        output["max-width"] = "100%"
        if kind == "image":
            output["height"] = "auto"
    return output


def generate_page(title, elements, tree):
    by_id = {e.id: e for e in elements}
    style_groups, classes = {}, {}
    for element in elements:
        props = element.properties
        normal = tuple(sorted(declarations(props, element.type).items()))
        hover = tuple(sorted((k.removeprefix("hover-"), color(v) if k.endswith("color") else v) for k, v in props.items() if k.startswith("hover-")))
        key = normal, hover, props.get("mobile-stack") == "true" or (element.type == "nav" and props.get("responsive") == "true")
        if any(key):
            style_groups.setdefault(key, f'style-{len(style_groups) + 1}')
            classes[element.id] = style_groups[key]

    def attributes(values):
        return ''.join(f' {key}="{escape(str(value), quote=True)}"' if value is not True else f' {key}' for key, value in values.items())

    def render(node, indent="    "):
        if not node.element_id:
            children = '\n'.join(render(child, indent + '  ') for child in node.children)
            return f'{indent}<div class="{node.direction}">\n{children}\n{indent}</div>'
        e = by_id[node.element_id]
        p, kind = e.properties, e.type
        tag = 'h' + p.get("level", "1") if kind == "heading" else TAGS.get(kind, kind)
        attrs = {"id": p.get("id", e.id)}
        css_classes = []
        if kind in {"nav", "hero", "container", "card", "form"}:
            css_classes.append(kind)
        if p.get("button-style") == "true":
            css_classes.append("button-link")
        if e.id in classes:
            css_classes.append(classes[e.id])
        if css_classes:
            attrs["class"] = ' '.join(css_classes)
        if "aria-label" in p:
            attrs["aria-label"] = p["aria-label"]
        text = escape(e.text)
        if kind == "image":
            attrs.update(src=p["src"], alt="" if p.get("decorative") == "true" else p.get("alt", e.text))
            for dimension in ("width", "height"):
                if re.fullmatch(r'\d+px', p.get(dimension, '')):
                    attrs[dimension] = p[dimension][:-2]
            return f'{indent}<img{attributes(attrs)}>'
        if kind == "link":
            attrs["href"] = p["href"]
            if p.get("target") == "_blank":
                attrs.update(target="_blank", rel="noopener noreferrer")
        if kind in {"button", "submit"}:
            attrs["type"] = "submit" if kind == "submit" else "button"
            if kind == "submit":
                attrs["disabled"] = True
        if kind == "th":
            attrs["scope"] = "col"
        prefix = ''
        if kind in {"input", "textarea", "select"}:
            prefix = f'{indent}<label for="{escape(str(attrs["id"]), quote=True)}">{text}</label>\n'
            attrs["name"] = p.get("name", e.id)
            if kind == "input":
                attrs["type"] = p.get("type", "text")
            for key in ("value", "placeholder", "minlength", "maxlength"):
                if key in p:
                    attrs[key] = p[key]
            if p.get("required") == "true":
                attrs["required"] = True
            text = ''
        if kind == "label":
            attrs["for"] = p["for"]
        if kind == "option":
            attrs["value"] = p.get("value", e.text)
        if kind == "input":
            return prefix + f'{indent}<input{attributes(attrs)}>'
        if kind == "form":
            # Disabled submit controls plus inert form: no accidental GET of passwords.
            attrs["inert"] = True
            text = ''
            prefix = f'{indent}<p class="static-form-note">Static form preview. Submission, authentication and storage are not connected.</p>\n'
        children = '\n'.join(render(child, indent + '  ') for child in node.children)
        if kind == "link" and children:
            # Paragraphs inside anchors are rendered as phrasing content.
            children = children.replace('<p ', '<span ').replace('</p>', '</span>')
        body = text + ('\n' + children + '\n' + indent if children else '')
        markup = prefix + f'{indent}<{tag}{attributes(attrs)}>{body}</{tag}>'
        if kind == "table":
            markup = f'{indent}<div class="table-scroll" role="region" aria-label="Table" tabindex="0">\n{markup}\n{indent}</div>'
        return markup

    markup = '\n'.join(render(node) for node in tree.children)
    wrapper = "div" if any(e.type in {"main", "header", "footer"} for e in elements) else "main"
    html = f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escape(title)}</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
  <{wrapper} class="page">
{markup}
  </{wrapper}>
</body>
</html>
'''
    used = {e.type for e in elements}
    if "submit" in used or any(e.properties.get("button-style") == "true" for e in elements):
        used.add("button")
    css = BASE + '\n'.join(rule for kind, rule in COMPONENT_CSS.items() if kind in used) + '\n'

    def rule(selector, declarations):
        return f'{selector} {{ ' + '; '.join(f'{k}: {v}' for k, v in declarations) + '; }\n'
    page_declarations = declarations(tree.properties, "container")
    if page_declarations:
        css += rule('body', sorted(page_declarations.items()))
    mobile = []
    for (normal, hover, stack), name in style_groups.items():
        if normal:
            css += rule('.' + name, normal)
        if hover:
            css += rule('.' + name + ':hover', hover)
        if stack:
            mobile.append(f'  .{name} {{ display: flex; flex-direction: column; align-items: stretch; grid-template-columns: minmax(0, 1fr); }}')
    directions = set()
    def collect(nodes):
        for node in nodes:
            if node.direction:
                directions.add(node.direction)
            collect(node.children)
    collect(tree.children)
    for direction in sorted(directions):
        css += f'.{direction} {{ display: flex; flex-direction: {direction}; gap: 16px; flex-wrap: wrap; }}\n'
    if "row" in directions:
        mobile.append('  .row { flex-direction: column; }')
    if tree.properties.get("responsive") == "true":
        mobile += ['  .page { padding: 24px 16px; }', '  .container, .nav { display: flex; flex-direction: column; align-items: stretch; }']
    if mobile:
        css += '@media (max-width: 640px) {\n' + '\n'.join(mobile) + '\n}\n'
    if any(e.properties.get("transition") == "smooth" for e in elements):
        css += '@media (prefers-reduced-motion: reduce) { a, button { transition: none; } }\n'
    return html, css
