"""Deterministic HTML/CSS generation from the validated page-tree IR."""

from html import escape
from pathlib import Path
from shutil import copyfile

from .assets import is_supported_image, local_asset_path
from .model import CompilationResult, Element, PageNode, PageTree

from .properties import COLORS, readable_foreground

SIZES = {"small": "0.875rem", "medium": "1.125rem", "big": "2.5rem"}
TAGS = {"heading": "h1", "paragraph": "p", "button": "button"}
BASE_CSS = """/* Generated by Text2Web. */
* { box-sizing: border-box; }
body { margin: 0; background: #ffffff; color: #111827; font-family: Arial, sans-serif; }
.page { max-width: 960px; margin: 0 auto; padding: 40px 24px; }
h1 { font-size: 2rem; margin: 0 0 20px; }
p { line-height: 1.6; margin: 0 0 20px; white-space: pre-wrap; }
button { font: inherit; padding: 12px 20px; border: 1px solid #64748b; border-radius: 6px; }
"""


def _element_markup(element: Element, indent: str) -> str:
    if element.type == "image":
        source = escape(element.properties["src"])
        description = escape(element.text)
        return f'{indent}<img id="{element.id}" src="{source}" alt="{description}">'
    tag = TAGS[element.type]
    attributes = f' id="{element.id}"'
    if tag == "button":
        attributes += ' type="button"'
    return f"{indent}<{tag}{attributes}>{escape(element.text)}</{tag}>"


def _render_node(node: PageNode, elements: dict[str, Element], indent: str = "    ") -> str:
    if node.element_id is not None:
        return _element_markup(elements[node.element_id], indent)
    css_class = "row" if node.direction == "row" else "column"
    children = "\n".join(_render_node(child, elements, indent + "  ") for child in node.children)
    return f'{indent}<div class="{css_class}">\n{children}\n{indent}</div>'


def generate(
    title: str, elements: list[Element], page_tree: PageTree | None = None,
) -> tuple[str, str]:
    page_tree = page_tree or PageTree(
        title, [PageNode(element_id=element.id) for element in elements],
    )
    if page_tree.properties or any(element.extended or element.parent_id for element in elements):
        from .render import generate_page
        return generate_page(title, elements, page_tree)
    element_by_id = {element.id: element for element in elements}
    markup = "\n".join(_render_node(node, element_by_id) for node in page_tree.children)
    def used_directions(nodes: list[PageNode]) -> set[str]:
        return {
            direction
            for node in nodes
            for direction in (
                {node.direction} if node.direction else set()
            ) | used_directions(node.children)
        }

    directions = used_directions(page_tree.children)
    style_groups: dict[tuple[str, ...], list[str]] = {}
    for element in elements:
        declarations = []
        props = element.properties
        if "color" in props:
            color = COLORS[props["color"]]
            if element.type == "button":
                foreground = COLORS[readable_foreground(color)]
                declarations.extend([f"background-color: {color}", f"color: {foreground}"])
            else:
                declarations.append(f"color: {color}")
        if "size" in props:
            declarations.append(f"font-size: {SIZES[props['size']]}")
        if props.get("font-weight") == "bold":
            declarations.append("font-weight: 700")
        if "font-family" in props:
            family = props["font-family"]
            declarations.append(f"font-family: {family}, sans-serif" if family == "arial" else f"font-family: {family}")
        if declarations:
            style_groups.setdefault(tuple(declarations), []).append(f"#{element.id}")
    rules = [
        f"{', '.join(selectors)} {{ {'; '.join(declarations)}; }}"
        for declarations, selectors in style_groups.items()
    ]
    html = f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escape(title)}</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
  <main class="page">
{markup}
  </main>
</body>
</html>
'''
    layout_css = ""
    if "row" in directions:
        layout_css += ".row { display: flex; flex-direction: row; align-items: flex-start; flex-wrap: wrap; gap: 16px; }\n"
    if "column" in directions:
        layout_css += ".column { display: flex; flex-direction: column; gap: 16px; }\n"
    if any(element.type == "image" for element in elements):
        layout_css += "img { max-width: 100%; height: auto; }\n"
    return html, BASE_CSS + layout_css + "\n".join(rules) + "\n"


def write_output(
    result: CompilationResult,
    directory: Path,
    *,
    overwrite: bool = False,
    asset_root: Path | None = None,
    assets: dict[str, bytes] | None = None,
) -> None:
    """Write a successful build and its local images; protect existing files by default."""
    if not result.success:
        raise ValueError("Cannot write output for a failed compilation.")
    directory = Path(directory)
    destinations = [directory / "index.html", directory / "style.css"]
    image_files = {}
    for element in result.symbols:
        if element.type != "image":
            continue
        asset_path = local_asset_path(element.properties["src"])
        if asset_path is None:
            continue
        relative = asset_path.as_posix()
        if assets is not None:
            if relative not in assets:
                raise FileNotFoundError(f"Image asset was not provided: {relative}")
            if not is_supported_image(assets[relative], asset_path.suffix):
                raise ValueError(f"Image asset is not valid {asset_path.suffix[1:].upper()} data: {relative}")
            image_files[relative] = assets[relative]
        elif asset_root is not None:
            source = (Path(asset_root) / Path(*asset_path.parts)).resolve()
            try:
                source.relative_to(Path(asset_root).resolve())
            except ValueError as error:
                raise ValueError(f"Image asset escapes its source folder: {relative}") from error
            if not source.is_file():
                raise FileNotFoundError(f"Image asset was not found: {source}")
            with source.open("rb") as image:
                header = image.read(16)
            if not is_supported_image(header, asset_path.suffix):
                raise ValueError(f"Image asset is not valid {asset_path.suffix[1:].upper()} data: {relative}")
            image_files[relative] = source
        else:
            raise FileNotFoundError(f"Provide the local image asset before writing output: {relative}")
    destinations.extend(directory / Path(*Path(name).parts) for name in image_files)
    if not overwrite and any(path.exists() for path in destinations):
        raise FileExistsError("Output files already exist. Choose another folder or use --force.")
    directory.mkdir(parents=True, exist_ok=True)
    for path, contents in zip(destinations[:2], [result.html, result.css]):
        path.write_text(contents, encoding="utf-8", newline="\n")
    for path, (name, source) in zip(destinations[2:], image_files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(source, bytes):
            path.write_bytes(source)
        else:
            copyfile(source, path)
